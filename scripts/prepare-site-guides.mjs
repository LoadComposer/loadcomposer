function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function namespaceSvgIds(svg, namespace) {
  const ids = [...svg.matchAll(/\bid="([^"]+)"/g)].map(match => match[1]);
  let output = svg;
  for (const id of ids) {
    const next = `${namespace}-${id}`;
    output = output
      .replaceAll(`id="${id}"`, `id="${next}"`)
      .replaceAll(`url(#${id})`, `url(#${next})`)
      .replaceAll(`href="#${id}"`, `href="#${next}"`)
      .replaceAll(`xlink:href="#${id}"`, `xlink:href="#${next}"`);
  }
  return output;
}

function fillTemplate(replacements) {
  let output = TEMPLATE;
  for (const [key, value] of Object.entries(replacements)) {
    const marker = `__${key}__`;
    if (!output.includes(marker)) throw new Error(`Guide template marker missing: ${marker}`);
    output = output.replaceAll(marker, value);
  }
  const unresolved = output.match(/__[A-Z0-9_]+__/g);
  if (unresolved) throw new Error(`Unresolved guide template markers: ${[...new Set(unresolved)].join(", ")}`);
  return output;
}

function dimensions(vehicle) {
  return `${vehicle.length.toLocaleString("en-US")} × ${vehicle.width.toLocaleString("en-US")} × ${vehicle.height.toLocaleString("en-US")} mm`;
}

function capacityRows(vehicleId) {
  return Object.values(PALLETS).map(pallet => {
    const capacity = FLOOR_CAPACITIES[vehicleId][pallet.id];
    return `<tr><td>${escapeHtml(pallet.name)}</td><td>${pallet.length} × ${pallet.width} mm</td><td>${capacity}</td></tr>`;
  }).join("\n");
}

function capacityTable(vehicleId, caption) {
  return [
    `<div class="table-wrap"><table><caption class="muted">${escapeHtml(caption)}</caption>`,
    "<thead><tr><th scope=\"col\">Pallet preset</th><th scope=\"col\">Footprint</th><th scope=\"col\">Floor positions found</th></tr></thead>",
    `<tbody>${capacityRows(vehicleId)}</tbody></table></div>`
  ].join("\n");
}

function figure(exampleId) {
  const example = PUBLIC_EXAMPLES[exampleId];
  return [
    "<figure>",
    `<img src="/assets/guides/${escapeHtml(example.image)}" width="${example.imageWidth}" height="${example.imageHeight}" alt="${escapeHtml(example.alt)}" />`,
    `<figcaption>${escapeHtml(example.caption)}</figcaption>`,
    "</figure>"
  ].join("\n");
}

function actions(exampleId) {
  return [
    '<div class="actions" aria-label="Planner actions">',
    `<a class="button" href="/?example=${encodeURIComponent(exampleId)}">Try this example</a>`,
    '<a class="button secondary" href="/">Use LoadComposer for free</a>',
    "</div>"
  ].join("\n");
}

function related(items) {
  if (!items.length) return "";
  return [
    "<h2>Related guides</h2>",
    '<ul class="related">',
    ...items.map(item => `<li><a href="${escapeHtml(item.href)}">${escapeHtml(item.label)}</a></li>`),
    "</ul>"
  ].join("\n");
}

