function breadcrumb(page) {
  const items = [
    { name: "LoadComposer", url: `${ORIGIN}/` },
    { name: "Guides", url: `${ORIGIN}/guides/` }
  ];
  if (page.route !== "/guides/") items.push({ name: page.label, url: `${ORIGIN}${page.route}` });
  const json = {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: items.map((item, index) => ({
      "@type": "ListItem",
      position: index + 1,
      name: item.name,
      item: item.url
    }))
  };
  const html = [
    '<a href="/">LoadComposer</a>',
    '<span aria-hidden="true">›</span>',
    page.route === "/guides/" ? '<span aria-current="page">Guides</span>' : '<a href="/guides/">Guides</a>'
  ];
  if (page.route !== "/guides/") {
    html.push('<span aria-hidden="true">›</span>', `<span aria-current="page">${escapeHtml(page.label)}</span>`);
  }
  return { json: JSON.stringify(json), html: html.join("\n") };
}

function writePage(page) {
  const canonical = `${ORIGIN}${page.route}`;
  const crumb = breadcrumb(page);
  const example = page.exampleId ? PUBLIC_EXAMPLES[page.exampleId] : null;
  const ogImage = example
    ? `${ORIGIN}/assets/guides/${example.image}`
    : `${ORIGIN}/assets/loadcomposer-og-v${VERSION}.png`;
  const output = fillTemplate({
    PAGE_TITLE: escapeHtml(page.title),
    PAGE_DESCRIPTION: escapeHtml(page.description),
    CANONICAL_URL: canonical,
    OG_TYPE: page.route === "/guides/" ? "website" : "article",
    OG_IMAGE: ogImage,
    OG_IMAGE_WIDTH: example ? String(example.imageWidth) : "1200",
    OG_IMAGE_HEIGHT: example ? String(example.imageHeight) : "630",
    BREADCRUMB_JSON: crumb.json.replaceAll("<", "\\u003c"),
    BREADCRUMB_HTML: crumb.html,
    MAIN_CONTENT: page.body.trim(),
    COMPACT_BRAND_DAY: namespaceSvgIds(BRAND_DAY, `guide-${page.slug || "hub"}-day`),
    COMPACT_BRAND_NIGHT: namespaceSvgIds(BRAND_NIGHT, `guide-${page.slug || "hub"}-night`)
  });
  const directory = page.route === "/guides/" ? GUIDES : path.join(GUIDES, page.slug);
  fs.mkdirSync(directory, { recursive: true });
  fs.writeFileSync(path.join(directory, "index.html"), output, "utf8");
}

